#!/usr/bin/env python3
"""Build the language pages of whalehome.io: /en/, /es/, /ru/.

panama-crypto-homes/index.html stays the only source. This script copies it to
panama-crypto-homes/{en,es,ru}/index.html and only swaps the <head> tags
(lang, title, description, canonical, Open Graph, Twitter, preview image). The page picks its language
from the path, so the copies need no other changes.

Run after every edit of panama-crypto-homes/index.html:
    python3 scripts/build_whalehome_lang.py
"""
import pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "panama-crypto-homes"
SITE = "https://whalehome.io"

META = {
    "en": dict(
        locale="en_US", image="og.jpg",
        title="WhaleHome Panama",
        desc="Luxury homes in Panama for crypto founders, traders and iGaming teams. Pay in USDT, USDC, BTC, ETH or SOL. Residency from $300k, up to 10% rental yield.",
        og_title="WhaleHome · Own luxury in Panama. Pay in crypto.",
        og_desc="Sea-view homes + Panama residency for crypto people. Pay in USDT, BTC, ETH, USDC or SOL.",
    ),
    "es": dict(
        locale="es_PA", image="og-es.jpg",
        title="WhaleHome Panamá",
        desc="Propiedades de lujo en Panamá para fundadores crypto, traders y equipos de iGaming. Paga en USDT, USDC, BTC, ETH o SOL. Residencia desde $300k, hasta 10% de renta anual.",
        og_title="WhaleHome · Lujo en Panamá. Paga en crypto.",
        og_desc="Casas con vista al mar + residencia en Panamá para la gente crypto. Paga en USDT, BTC, ETH, USDC o SOL.",
    ),
    "ru": dict(
        locale="ru_RU", image="og-ru.jpg",
        title="WhaleHome Панама",
        desc="Премиальная недвижимость в Панаме для крипто-фаундеров, трейдеров и iGaming-команд. Оплата в USDT, USDC, BTC, ETH или SOL. ВНЖ от $300k, до 10% годовых с аренды.",
        og_title="WhaleHome · Недвижимость в Панаме за крипту.",
        og_desc="Дома с видом на океан + ВНЖ Панамы для людей из крипты. Оплата в USDT, BTC, ETH, USDC или SOL.",
    ),
}


def sub1(pattern, repl, s):
    out, n = re.subn(pattern, lambda m: repl, s, count=1)
    if n != 1:
        sys.exit(f"pattern not found: {pattern}")
    return out


def build(src, lang):
    m, url = META[lang], f"{SITE}/{lang}/"
    s = src
    s = sub1(r'<html lang="[a-z]+">', f'<html lang="{lang}">', s)
    s = sub1(r"<title>.*?</title>", f"<title>{m['title']}</title>", s)
    s = sub1(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{m["desc"]}">', s)
    s = sub1(r'<meta property="og:title" content="[^"]*">', f'<meta property="og:title" content="{m["og_title"]}">', s)
    s = sub1(r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{m["og_desc"]}">', s)
    s = sub1(r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{url}">', s)
    s = sub1(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{url}">', s)
    s = sub1(r'<meta property="og:image" content="[^"]*">', f'<meta property="og:image" content="{SITE}/{m["image"]}">', s)
    s = sub1(r'<meta name="twitter:image" content="[^"]*">', f'<meta name="twitter:image" content="{SITE}/{m["image"]}">', s)
    s = sub1(r'<meta property="og:image:alt" content="[^"]*">', f'<meta property="og:image:alt" content="{m["og_title"]}">', s)
    s = sub1(r'<meta name="twitter:title" content="[^"]*">', f'<meta name="twitter:title" content="{m["og_title"]}">', s)
    s = sub1(r'<meta name="twitter:description" content="[^"]*">', f'<meta name="twitter:description" content="{m["og_desc"]}">', s)
    others = [META[o]["locale"] for o in META if o != lang]
    s = sub1(r'<meta property="og:locale" content="[^"]*">\s*<meta property="og:locale:alternate" content="[^"]*">\s*<meta property="og:locale:alternate" content="[^"]*">',
             f'<meta property="og:locale" content="{m["locale"]}">\n<meta property="og:locale:alternate" content="{others[0]}">\n<meta property="og:locale:alternate" content="{others[1]}">', s)
    s = s.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build_whalehome_lang.py from ../index.html. Do not edit. -->", 1)
    return s


src = (ROOT / "index.html").read_text()
for lang in META:
    d = ROOT / lang
    d.mkdir(exist_ok=True)
    (d / "index.html").write_text(build(src, lang))
    print("built", d / "index.html")

# listings for the Telegram bot (homes.json + JPG covers)
subprocess.run(["node", str(pathlib.Path(__file__).with_name("build_whalehome_homes.js"))], check=True)
