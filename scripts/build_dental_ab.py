#!/usr/bin/env python3
"""Build the A/B test page of the dental clinics site (SmileScale).

dental-clinics/index.html is the only source and is variant B (no prices).
This script writes dental-clinics/price/index.html: variant A (with prices), noindex,
with image paths moved one folder up. Run after every edit of dental-clinics/index.html:
    python3 scripts/build_dental_ab.py
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "dental-clinics"
s = (ROOT / "index.html").read_text()
s = s.replace('<html lang="en" data-variant="b">', '<html lang="en" data-variant="a">', 1)
s = s.replace('<meta name="theme-color"', '<meta name="robots" content="noindex, follow">\n<meta name="theme-color"', 1)
s = re.sub(r'(["\'`(])img/', r'\1../img/', s)          # src="img/..", 'img/..', `img/${..}`, url(img/..)
s = s.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build_dental_ab.py from ../index.html. Do not edit. -->", 1)
out = ROOT / "price" / "index.html"
out.parent.mkdir(exist_ok=True)
out.write_text(s)
print("built", out)
